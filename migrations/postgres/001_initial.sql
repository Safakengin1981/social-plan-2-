-- SocialPlan PostgreSQL schema prototype (isolated development only).
-- Do NOT execute against an existing production database.
BEGIN;
CREATE TABLE IF NOT EXISTS businesses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 email TEXT NOT NULL UNIQUE,
 salt TEXT NOT NULL,
 passhash TEXT NOT NULL,
 role TEXT NOT NULL CHECK (role IN ('admin','editor'))
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS login_attempts (
 email_hash TEXT PRIMARY KEY,
 failures INTEGER NOT NULL,
 first_attempt BIGINT NOT NULL,
 locked_until BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS posts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 author_id BIGINT NOT NULL REFERENCES users(id),
 caption TEXT NOT NULL,
 media_url TEXT NOT NULL,
 scheduled_at TEXT NOT NULL,
 status TEXT NOT NULL CHECK (status IN ('draft','approved','cancelled')),
 created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 action TEXT NOT NULL,
 post_id BIGINT,
 created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_tenant ON audit_events(business_id,id);
CREATE TABLE IF NOT EXISTS publish_jobs (
 post_id BIGINT PRIMARY KEY REFERENCES posts(id),
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 state TEXT NOT NULL CHECK (state IN ('queued','ready','blocked','cancelled')),
 reason TEXT NOT NULL DEFAULT '',
 updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_publish_jobs_business ON publish_jobs(business_id,state);
CREATE TABLE IF NOT EXISTS instagram_oauth_states (
 state_hash TEXT PRIMARY KEY,
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS instagram_connections (
 business_id BIGINT PRIMARY KEY REFERENCES businesses(id),
 instagram_id TEXT NOT NULL,
 username TEXT NOT NULL,
 encrypted_token TEXT NOT NULL,
 expires BIGINT NOT NULL,
 verified_at BIGINT NOT NULL
);
COMMIT;
